import assert from 'node:assert/strict';
import { confirmationOk, recentlySignedIn, sameOriginOnly } from '../lib/account/core.ts';
const r = (h: Record<string, string>) => new Request('https://bukmarkz.com/api/account/delete', { method: 'POST', headers: h });
let n = 0; const ok = (m: string) => console.log('ok', ++n, m);
assert.equal(sameOriginOnly(r({ 'sec-fetch-site': 'same-origin' })), true); ok('same-origin ok');
assert.equal(sameOriginOnly(r({ 'sec-fetch-site': 'cross-site' })), false); ok('cross-site refused');
assert.equal(sameOriginOnly(r({ origin: 'https://bukmarkz.com' })), true); ok('origin match');
assert.equal(sameOriginOnly(r({ origin: 'https://evil.com' })), false); ok('origin mismatch');
assert.equal(sameOriginOnly(r({})), false); ok('no headers refused');
assert.equal(sameOriginOnly(r({ authorization: 'Bearer x', 'sec-fetch-site': 'same-origin' })), false); ok('bearer refused');
const now = Date.now();
assert.equal(recentlySignedIn(new Date(now - 60_000).toISOString(), now), true); ok('recent');
assert.equal(recentlySignedIn(new Date(now - 31 * 60_000).toISOString(), now), false); ok('stale');
assert.equal(recentlySignedIn(null, now), false); ok('null');
assert.equal(recentlySignedIn('garbage', now), false); ok('garbage');
assert.equal(confirmationOk({ confirm: 'DELETE', email: ' A@B.com ' }, 'a@b.com'), true); ok('confirm ok');
assert.equal(confirmationOk({ confirm: 'delete', email: 'a@b.com' }, 'a@b.com'), false); ok('case-sensitive word');
assert.equal(confirmationOk({ confirm: 'DELETE', email: 'x@b.com' }, 'a@b.com'), false); ok('wrong email');
assert.equal(confirmationOk(null, 'a@b.com'), false); ok('null body');
